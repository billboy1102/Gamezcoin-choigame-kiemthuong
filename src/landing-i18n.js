export function getLanguage() {
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'en' ? 'en' : 'vi'
  } catch {
    return 'vi'
  }
}

export function setLanguage(language) {
  const next = language === 'en' ? 'en' : 'vi'
  try { localStorage.setItem(LANGUAGE_STORAGE_KEY, next) } catch {}
  if (typeof document !== 'undefined') document.documentElement.lang = next
  return next
}

export function translate(key, variables = {}, language = getLanguage()) {
  const source = dictionaries[language] || dictionaries.vi
  let value = source[key] || dictionaries.vi[key] || key
  Object.entries(variables).forEach(([name, replacement]) => {
    value = value.replaceAll(`{${name}}`, String(replacement))
  })
  return value
}

if (typeof document !== 'undefined') document.documentElement.lang = getLanguage()
